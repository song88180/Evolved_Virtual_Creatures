"""Choosing what to mutate: the public ``mutation()`` entry point, the mutable-parameter pool, per-parameter rates, and the topology-mutation floor."""

from __future__ import annotations

from typing import Any, List, Optional, Tuple
import random

from .settings import MutationSettings


class MutationSelectionMixin(MutationSettings):
    """Choosing what to mutate part of ``GenotypeMutationMixin``."""

    def mutation(
        self,
        num_mutations: int = 1,
        mutation_rate: Optional[float] = None,
        rng: Optional[random.Random] = None,
        allow_topology_mutations: bool = True,
        allow_slide_joint: bool = False,
        allow_root_mutation: bool = True,
        topology_mutation_rate_min: float = MutationSettings.DEFAULT_TOPOLOGY_MUTATION_RATE_MIN,
    ) -> "Genotype":
        """
        Randomly mutate mutable genotype parameters in place.

        If mutation_rate is provided, every mutable parameter is independently
        mutated with that probability and num_mutations is ignored. Topology
        mutation operators use at least topology_mutation_rate_min when topology
        mutations are allowed. Otherwise, num_mutations distinct mutable
        parameters are chosen uniformly, then topology mutation operators get an
        additional independent chance at topology_mutation_rate_min. Set
        allow_topology_mutations to False to only mutate existing node and
        connection properties without changing how genes are linked or the number
        of bodies generated by the phenotype. Set allow_slide_joint to True to
        let mutations create slide-jointed nodes. Set allow_root_mutation to
        False to keep the root node gene unchanged.
        """
        random_source = rng if rng is not None else random
        if not 0.0 <= topology_mutation_rate_min <= 1.0:
            raise ValueError("topology_mutation_rate_min must be between 0 and 1")
        previous_allow_slide_joint = getattr(
            self, "_allow_slide_joint_for_mutation", False
        )
        graph_mode = self.control_mode == "graph"
        if graph_mode:
            self._seed_graph_brains(random_source)
        mutable_parameters = self._collect_mutable_parameters(
            allow_topology_mutations=allow_topology_mutations,
            allow_root_mutation=allow_root_mutation,
        )
        if not mutable_parameters:
            return self

        if mutation_rate is not None:
            if not 0.0 <= mutation_rate <= 1.0:
                raise ValueError("mutation_rate must be between 0 and 1")
            selected_parameters = [
                parameter
                for parameter in mutable_parameters
                if random_source.random()
                < self._mutation_rate_for_parameter(
                    parameter,
                    mutation_rate,
                    topology_mutation_rate_min,
                    allow_topology_mutations,
                )
            ]
        else:
            if num_mutations < 0:
                raise ValueError("num_mutations must be non-negative")
            selected_parameters = random_source.sample(
                mutable_parameters,
                k=min(num_mutations, len(mutable_parameters)),
            )
            self._add_topology_floor_mutations(
                selected_parameters,
                mutable_parameters,
                topology_mutation_rate_min,
                random_source,
                allow_topology_mutations,
            )

        # Brain mutations go last: valid input sources depend on the body.
        selected_parameters.sort(
            key=lambda parameter: parameter[0].startswith(self.BRAIN_MUTATION_PREFIX)
        )
        self._allow_slide_joint_for_mutation = allow_slide_joint
        try:
            print(f"Applying {len(selected_parameters)} genotype mutation(s):")
            for parameter_path in selected_parameters:
                mutation_description = self._mutate_parameter_path(
                    parameter_path,
                    random_source,
                )
                print(f"  - {mutation_description}")

            if allow_topology_mutations:
                prune_description = self._prune_disconnected_nodes()
                if prune_description:
                    print(f"  - {prune_description}")
            if graph_mode:
                # New or retyped parts need effectors; then drop dead neurons.
                self._seed_graph_brains(random_source)
                garbage_description = self._collect_brain_garbage()
                if garbage_description:
                    print(f"  - {garbage_description}")
        finally:
            self._allow_slide_joint_for_mutation = previous_allow_slide_joint

        return self

    def _mutation_rate_for_parameter(
        self,
        parameter_path: Tuple[Any, ...],
        mutation_rate: float,
        topology_mutation_rate_min: float,
        allow_topology_mutations: bool,
    ) -> float:
        if allow_topology_mutations and self._is_topology_mutation_parameter(
            parameter_path
        ):
            return max(mutation_rate, topology_mutation_rate_min)
        return mutation_rate

    def _add_topology_floor_mutations(
        self,
        selected_parameters: List[Tuple[Any, ...]],
        mutable_parameters: List[Tuple[Any, ...]],
        topology_mutation_rate_min: float,
        random_source: random.Random,
        allow_topology_mutations: bool,
    ) -> None:
        if not allow_topology_mutations or topology_mutation_rate_min == 0.0:
            return

        for parameter in mutable_parameters:
            if not self._is_topology_mutation_parameter(parameter):
                continue
            if parameter in selected_parameters:
                continue
            if random_source.random() < topology_mutation_rate_min:
                selected_parameters.append(parameter)

    def _is_topology_mutation_parameter(self, parameter_path: Tuple[Any, ...]) -> bool:
        return parameter_path[0] in self.TOPOLOGY_MUTATION_PARAMETER_TYPES

    def _collect_mutable_parameters(
        self,
        allow_topology_mutations: bool = True,
        allow_root_mutation: bool = True,
    ) -> List[Tuple[Any, ...]]:
        # Sine controller fields are read only in sine mode; neural weights are
        # registered separately below and only in neural mode.
        sine_mode = self.control_mode == "sine"
        mutable_parameters: List[Tuple[Any, ...]] = []
        if sine_mode:
            mutable_parameters.append(("genotype", "global_control_freq"))
        if self.control_mode == "graph":
            mutable_parameters.extend(self._brain_parameter_paths())
        if allow_topology_mutations:
            mutable_parameters.extend((
                ("connection_addition",),
                ("connection_new_node_addition",),
                ("fresh_node_connection_addition",),
            ))
        node_mutation_specs = (
            "size",
            "joint_type",
            "shape",
            "recursive_limit",
            "orientation",
        )
        connection_mutation_specs = self.CONNECTION_MUTABLE_FIELDS

        topology_sensitive_node_fields = {"recursive_limit"}
        topology_sensitive_connection_fields = {"symmetry", "terminal_only"}

        for node_name, node in self.nodes.items():
            if allow_root_mutation or node_name != self.root:
                for field_name in node_mutation_specs:
                    if (
                        not allow_topology_mutations
                        and field_name in topology_sensitive_node_fields
                    ):
                        continue
                    if field_name == "joint_type" and node.joint_type == "free":
                        continue
                    self._add_mutable_parameter_paths(
                        mutable_parameters,
                        owner=node,
                        base_path=("node", node_name, field_name),
                    )

            for connection_name in node.child_connections:
                connection = self.connections[connection_name]
                if allow_topology_mutations:
                    mutable_parameters.append(("connection_origin", connection, node_name))
                    mutable_parameters.append(("connection_replacement", connection, node_name))
                    mutable_parameters.append(("connection_origin_node_replacement", connection, node_name))
                    mutable_parameters.append(("connection_removal", connection, node_name))

        for connection in self.connections.values():
            if allow_topology_mutations:
                mutable_parameters.append(("connection_destination", connection))
                mutable_parameters.append(("connection_type", connection))
                mutable_parameters.append(("connection_destination_node_replacement", connection))
            for field_name in connection_mutation_specs:
                if (
                    not allow_topology_mutations
                    and field_name in topology_sensitive_connection_fields
                ):
                    continue
                if not sine_mode and field_name in self.SINE_CONTROL_FIELDS:
                    continue
                base_path = ("connection", connection, field_name)
                if field_name == "symmetry":
                    mutable_parameters.append(base_path)
                else:
                    self._add_mutable_parameter_paths(
                        mutable_parameters,
                        owner=connection,
                        base_path=base_path,
                    )
            if self._connection_supports_neural_mutation(connection):
                self._ensure_connection_neural_parameters(connection)
                self._add_neural_parameter_paths(mutable_parameters, connection)

        return mutable_parameters

    def _add_mutable_parameter_paths(
        self,
        mutable_parameters: List[Tuple[Any, ...]],
        owner: Any,
        base_path: Tuple[Any, ...],
    ):
        field_name = base_path[-1]
        value = getattr(owner, field_name)
        if isinstance(value, (list, tuple)):
            for index in range(len(value)):
                mutable_parameters.append((*base_path, index))
            return

        mutable_parameters.append(base_path)
